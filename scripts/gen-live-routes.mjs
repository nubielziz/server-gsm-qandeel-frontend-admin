// Generates src/mocks/liveRoutes.gen.ts: the routes the real backend has built, for the partial mock mode
// (VITE_API_MOCKS=unbuilt, decision 018). Reads the backend's contract file `docs/contract/openapi.json`.
// Usage: npm run mocks:live            (write the file)
//        npm run mocks:live -- --check (exit 1 when the committed file is stale)
// The backend folder is $BACKEND_DIR (default ../backend). Re-run it after every backend merge.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = resolve(root, 'src/mocks/liveRoutes.gen.ts');
const CONTRACT_PATH = 'docs/contract/openapi.json';

// The operation methods an OpenAPI path item can hold (the other members, such as `parameters`, are not operations).
const OPERATION_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];
// What the console calls: every admin route plus the root health route.
const ROOT_KEEP = ['GET /health'];
// `METHOD /path/:param`, the key format of the contract's `x-gsm-key` (and of docs/route-manifest.json).
const KEY_FORMAT = /^(GET|POST|PUT|PATCH|DELETE) (\/\S*)$/;

/** Splits "METHOD /path" into its two parts (the contract keys are already in this shape). */
function splitKey(key) {
  const match = KEY_FORMAT.exec(key);
  return match ? { method: match[1], path: match[2] } : undefined;
}

/** True for a route the console calls: any `/admin/` route, or the root health route. */
function isConsoleRoute(key) {
  const parts = splitKey(key);
  return Boolean(parts) && (parts.path.startsWith('/admin/') || ROOT_KEEP.includes(key));
}

/**
 * Collects the `x-gsm-key` of every operation the console calls, sorted by path and then method, without duplicates.
 * Why: the key is the contract's own name of a route, so the console never has to guess it from `{id}` style paths.
 * It throws on a console route that has no key, or whose key does not match its method, so a gap is noticed.
 */
export function collectLiveKeys(spec) {
  const keys = new Set();
  for (const [path, item] of Object.entries(spec?.paths ?? {})) {
    for (const method of OPERATION_METHODS) {
      const operation = item?.[method];
      if (!operation) continue;
      const key = operation['x-gsm-key'];
      if (key === undefined) {
        // A route the console never calls (docs, metrics) may go without a key; an admin route may not.
        if (path.startsWith('/admin/') || `${method.toUpperCase()} ${path}` === 'GET /health') {
          throw new Error(`${method.toUpperCase()} ${path} has no x-gsm-key`);
        }
        continue;
      }
      const parts = splitKey(key);
      if (!parts)
        throw new Error(`${method.toUpperCase()} ${path}: bad x-gsm-key "${key}" (want "METHOD /path")`);
      if (parts.method !== method.toUpperCase()) {
        throw new Error(`${method.toUpperCase()} ${path}: x-gsm-key "${key}" has another method`);
      }
      if (isConsoleRoute(key)) keys.add(key);
    }
  }
  return [...keys].sort((a, b) => {
    const [methodA, pathA] = a.split(' ');
    const [methodB, pathB] = b.split(' ');
    return pathA < pathB ? -1 : pathA > pathB ? 1 : methodA < methodB ? -1 : methodA > methodB ? 1 : 0;
  });
}

/** The text of src/mocks/liveRoutes.gen.ts for a list of keys. Stable: the same keys always give the same text. */
export function render(keys) {
  return [
    `// Generated by scripts/gen-live-routes.mjs from the backend's ${CONTRACT_PATH} ($BACKEND_DIR, default ../backend):`,
    '// generated, do not edit. Run `npm run mocks:live` after the backend changes (decision 018).',
    '// The routes the real backend has built; in VITE_API_MOCKS=unbuilt mode these go to the real API, every other',
    '// route stays mocked. Format: "METHOD /path/:param".',
    'export const LIVE_ROUTE_KEYS: readonly string[] = [',
    ...keys.map((key) => `  '${key}',`),
    '];',
    '',
  ].join('\n');
}

/**
 * Reads the contract of `backendDir`, builds the file text and either writes it or checks it.
 * Returns `{ ok, message }` so the caller (and the tests) decide how to report it.
 */
export function run({ backendDir, outFile = OUT_FILE, check = false }) {
  const contract = resolve(backendDir, CONTRACT_PATH);
  if (!existsSync(contract)) {
    return { ok: false, message: `${contract} not found. Set BACKEND_DIR to the backend checkout.` };
  }
  const keys = collectLiveKeys(JSON.parse(readFileSync(contract, 'utf8')));
  const text = render(keys);
  if (check) {
    const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : undefined;
    return current === text
      ? { ok: true, message: `liveRoutes.gen.ts is up to date (${keys.length} routes).` }
      : { ok: false, message: 'liveRoutes.gen.ts is stale: run `npm run mocks:live` and commit the result.' };
  }
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  return { ok: true, message: `Wrote ${outFile} (${keys.length} live routes)` };
}

function main() {
  const backendDir = resolve(root, process.env.BACKEND_DIR || '../backend');
  let result;
  try {
    result = run({ backendDir, check: process.argv.includes('--check') });
  } catch (error) {
    result = { ok: false, message: `live routes failed: ${error.message}` };
  }
  (result.ok ? console.log : console.error)(result.message);
  if (!result.ok) process.exit(1);
}

// Run only when started from the command line, so tests can import the functions.
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
