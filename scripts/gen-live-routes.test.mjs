// Tests for the live routes generator: which OpenAPI operations count, the sort order, the file text, and --check.
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { collectLiveKeys, render, run } from './gen-live-routes.mjs';

// A small contract: admin routes, the health route, routes the console never calls, and a `parameters` member.
const spec = {
  openapi: '3.1.0',
  paths: {
    '/admin/staff/{id}/suspend': { post: { 'x-gsm-key': 'POST /admin/staff/:id/suspend' } },
    '/admin/staff': {
      post: { 'x-gsm-key': 'POST /admin/staff' },
      get: { 'x-gsm-key': 'GET /admin/staff' },
    },
    '/admin/staff/{id}': {
      parameters: [{ name: 'id', in: 'path' }],
      get: { 'x-gsm-key': 'GET /admin/staff/:id' },
    },
    '/health': { get: { 'x-gsm-key': 'GET /health' } },
    '/docs': { get: { 'x-gsm-key': 'GET /docs' } },
    '/metrics': { get: {} },
    '/v1/orders': { get: { 'x-gsm-key': 'GET /v1/orders' } },
  },
};

describe('collectLiveKeys', () => {
  it('keeps admin routes and GET /health, sorted by path and then method', () => {
    expect(collectLiveKeys(spec)).toEqual([
      'GET /admin/staff',
      'POST /admin/staff',
      'GET /admin/staff/:id',
      'POST /admin/staff/:id/suspend',
      'GET /health',
    ]);
  });

  it('leaves out docs, metrics and non-admin routes, with or without a key', () => {
    const keys = collectLiveKeys(spec);
    for (const left of ['GET /docs', 'GET /v1/orders']) expect(keys).not.toContain(left);
    expect(keys).toHaveLength(5);
  });

  it('gives the same list for a repeated key and for an empty contract', () => {
    const twice = {
      paths: {
        '/admin/a': { get: { 'x-gsm-key': 'GET /admin/a' } },
        '/admin/b': { get: { 'x-gsm-key': 'GET /admin/a' } },
      },
    };
    expect(collectLiveKeys(twice)).toEqual(['GET /admin/a']);
    expect(collectLiveKeys({})).toEqual([]);
  });

  it('throws on an admin route or the health route without a key', () => {
    expect(() => collectLiveKeys({ paths: { '/admin/a': { get: {} } } })).toThrow(
      'GET /admin/a has no x-gsm-key',
    );
    expect(() => collectLiveKeys({ paths: { '/health': { get: {} } } })).toThrow(
      'GET /health has no x-gsm-key',
    );
  });

  it('throws on a key in a wrong format or with another method', () => {
    expect(() => collectLiveKeys({ paths: { '/admin/a': { get: { 'x-gsm-key': 'admin/a' } } } })).toThrow(
      'bad x-gsm-key',
    );
    expect(() =>
      collectLiveKeys({ paths: { '/admin/a': { get: { 'x-gsm-key': 'POST /admin/a' } } } }),
    ).toThrow('another method');
  });
});

describe('render', () => {
  it('writes a generated header and one quoted key per line', () => {
    const text = render(['GET /admin/staff', 'GET /health']);
    expect(text).toMatch(
      /^\/\/ Generated by scripts\/gen-live-routes\.mjs from the backend's docs\/contract\/openapi\.json/,
    );
    expect(text).toContain('npm run mocks:live');
    expect(text).toContain(
      "export const LIVE_ROUTE_KEYS: readonly string[] = [\n  'GET /admin/staff',\n  'GET /health',\n];\n",
    );
  });

  it('is stable and renders an empty list', () => {
    expect(render(['GET /health'])).toBe(render(['GET /health']));
    expect(render([])).toContain('LIVE_ROUTE_KEYS: readonly string[] = [\n];');
  });
});

describe('run', () => {
  const dirs = [];
  afterEach(() => {
    for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
  });

  // A temp backend folder holding the contract above, and an output path next to it.
  function setup() {
    const dir = mkdtempSync(join(tmpdir(), 'gen-live-routes-'));
    dirs.push(dir);
    mkdirSync(join(dir, 'docs/contract'), { recursive: true });
    writeFileSync(join(dir, 'docs/contract/openapi.json'), JSON.stringify(spec));
    return { backendDir: dir, outFile: join(dir, 'out/liveRoutes.gen.ts') };
  }

  it('writes the file, and --check then passes', () => {
    const paths = setup();
    expect(run(paths)).toMatchObject({ ok: true });
    expect(readFileSync(paths.outFile, 'utf8')).toBe(render(collectLiveKeys(spec)));
    expect(run({ ...paths, check: true })).toMatchObject({ ok: true });
  });

  it('--check fails on a stale or a missing file and does not write', () => {
    const paths = setup();
    expect(run({ ...paths, check: true })).toMatchObject({ ok: false });
    run(paths);
    writeFileSync(paths.outFile, render(['GET /health']));
    expect(run({ ...paths, check: true })).toMatchObject({
      ok: false,
      message: expect.stringContaining('stale'),
    });
    expect(readFileSync(paths.outFile, 'utf8')).toBe(render(['GET /health']));
  });

  it('says so when the backend folder has no contract', () => {
    const { outFile } = setup();
    expect(run({ backendDir: join(tmpdir(), 'no-such-backend'), outFile })).toMatchObject({
      ok: false,
      message: expect.stringContaining('BACKEND_DIR'),
    });
  });
});
