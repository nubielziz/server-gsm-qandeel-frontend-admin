// Route coverage check: compares docs/route-manifest.json with the `@route METHOD /path` tags in src/features/**/api.
// Writes docs/ROUTE_COVERAGE.md, except with --feature (a feature worktree only checks itself and leaves docs/ alone).
// Usage: node scripts/check-route-coverage.mjs [--feature <id>] [--strict]
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'docs/route-manifest.json'), 'utf8'));
const plan = JSON.parse(fs.readFileSync(path.join(root, 'docs/feature-plan.json'), 'utf8'));

const args = process.argv.slice(2);
const onlyFeature = args.includes('--feature') ? args[args.indexOf('--feature') + 1] : null;
const strict = args.includes('--strict');

// Endpoints we deliberately do not implement, with a one-line reason. Empty means 100% is the target.
const EXCLUSIONS = {};

/** Finds every .ts/.tsx file under a folder (no dependency on glob libraries). */
function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return walk(p);
    return /\.(ts|tsx)$/.test(d.name) && !/\.test\.tsx?$/.test(d.name) ? [p] : [];
  });
}

/**
 * Collects `@route` tags from API files only (src/features/<name>/api/**), so tags in tests,
 * mocks or docs never count as coverage.
 */
function collectTags() {
  const featuresDir = path.join(root, 'src/features');
  const tags = [];
  for (const file of walk(featuresDir)) {
    const rel = path.relative(root, file);
    if (!/^src\/features\/[^/]+\/api\//.test(rel)) continue;
    const lines = fs.readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, i) => {
      const m = line.match(/@route\s+(GET|POST|PUT|PATCH|DELETE)\s+(\S+)/);
      if (m) tags.push({ key: `${m[1]} ${m[2]}`, file: rel, line: i + 1, feature: rel.split('/')[2] });
    });
  }
  return tags;
}

// Which feature owns each endpoint: feature-plan rows are "CRUD <path>" or "METHOD <path>" (manifest origin).
const ownerOfRow = new Map();
for (const f of plan.features) for (const r of f.rows) ownerOfRow.set(r, f.id);
const endpoints = manifest.endpoints.map((e) => ({
  ...e,
  owner: ownerOfRow.get(`${e.origin.method} ${e.origin.path}`) ?? '(unassigned)',
}));
const known = new Set(endpoints.map((e) => e.key));

const tags = collectTags();
const tagsByKey = new Map();
for (const t of tags) tagsByKey.set(t.key, [...(tagsByKey.get(t.key) ?? []), t]);

const unknownTags = tags.filter((t) => !known.has(t.key));
const duplicateTags = [...tagsByKey.entries()].filter(([, list]) => list.length > 1);

const rowsFor = (list) =>
  list.map((e) => {
    const hit = tagsByKey.get(e.key);
    const status = hit ? 'covered' : EXCLUSIONS[e.key] ? 'excluded' : 'missing';
    return {
      ...e,
      status,
      where: hit ? hit.map((t) => `${t.file}:${t.line}`).join(', ') : (EXCLUSIONS[e.key] ?? ''),
    };
  });

const all = rowsFor(endpoints);
const scope = onlyFeature ? all.filter((e) => e.owner === onlyFeature) : all;
const pct = (list) =>
  list.length
    ? ((100 * list.filter((e) => e.status !== 'missing').length) / list.length).toFixed(1)
    : '100.0';

// Markdown report (always for the whole manifest, so the file is stable).
const featureIds = plan.features.map((f) => f.id);
const lines = [
  '# Route coverage',
  '',
  'Generated by `npm run routes:coverage` from `docs/route-manifest.json`, `docs/feature-plan.json` and the `@route` tags in `src/features/**/api`. Do not edit by hand.',
  '',
  `Total: ${all.filter((e) => e.status === 'covered').length} covered, ${all.filter((e) => e.status === 'excluded').length} excluded, ${all.filter((e) => e.status === 'missing').length} missing of ${all.length} endpoints (${pct(all)}%).`,
  '',
  '| Feature | Endpoints | Covered | Missing | Coverage |',
  '|---|---|---|---|---|',
  ...featureIds.map((id) => {
    const list = all.filter((e) => e.owner === id);
    const miss = list.filter((e) => e.status === 'missing').length;
    return `| ${id} | ${list.length} | ${list.length - miss} | ${miss} | ${pct(list)}% |`;
  }),
  '',
  '## Tags that match no manifest endpoint',
  '',
  ...(unknownTags.length ? unknownTags.map((t) => `- \`${t.key}\` at ${t.file}:${t.line}`) : ['- none']),
  '',
  '## Endpoints tagged more than once',
  '',
  ...(duplicateTags.length
    ? duplicateTags.map(([k, list]) => `- \`${k}\`: ${list.map((t) => `${t.file}:${t.line}`).join(', ')}`)
    : ['- none']),
  '',
  '## Endpoints',
  '',
  '| Status | Endpoint | Feature | Where / reason |',
  '|---|---|---|---|',
  ...all.map((e) => `| ${e.status} | \`${e.key}\` | ${e.owner} | ${e.where} |`),
  '',
];
if (!onlyFeature) fs.writeFileSync(path.join(root, 'docs/ROUTE_COVERAGE.md'), lines.join('\n'));

// Console summary for the requested scope.
const missing = scope.filter((e) => e.status === 'missing');
console.log(
  `${onlyFeature ?? 'all features'}: ${pct(scope)}% (${scope.length - missing.length}/${scope.length})`,
);
for (const e of missing) console.log(`  missing  ${e.key}  (${e.owner})`);
for (const t of unknownTags) console.log(`  unknown tag  ${t.key}  ${t.file}:${t.line}`);
for (const [k, list] of duplicateTags)
  console.log(`  duplicate  ${k}  ${list.map((t) => t.file).join(', ')}`);

// --feature fails when that feature is incomplete; --strict fails on anything short of 100% or on bad tags.
const bad = unknownTags.length > 0 || duplicateTags.length > 0;
if ((onlyFeature && (missing.length || bad)) || (strict && (missing.length || bad))) process.exit(1);
